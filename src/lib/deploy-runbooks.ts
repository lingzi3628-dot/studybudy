/** A hardened-ish systemd unit for a Node app. */
export function generateSystemdUnit(opts: {
  appName: string;
  workingDirectory: string;
  execStart: string;
  port: number;
  user?: string;
}): string {
  const user = opts.user ?? "dev";
  return `[Unit]
Description=${opts.appName} Node.js application
After=network.target

[Service]
Type=simple
User=${user}
WorkingDirectory=${opts.workingDirectory}
ExecStart=${opts.execStart}
Restart=on-failure
RestartSec=5
Environment=NODE_ENV=production
Environment=PORT=${opts.port}
# Security hardening
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
`;
}

/** Caddyfile reverse-proxying a Node app with automatic HTTPS. */
export function generateCaddyfile(domain: string, upstreamPort: number): string {
  return `${domain} {
    reverse_proxy localhost:${upstreamPort}
    encode gzip

    header {
        Strict-Transport-Security "max-age=31536000; includeSubDomains"
        X-Content-Type-Options nosniff
        X-Frame-Options DENY
        Referrer-Policy strict-origin-when-cross-origin
    }

    log {
        output file /var/log/caddy/${domain.replace(/[^a-z0-9.-]/gi, "_")}.log
    }
}
`;
}

/** Vercel CLI deploy script (Next.js + managed Neon Postgres pattern). */
export function generateVercelScript(): string {
  return `#!/usr/bin/env bash
set -euo pipefail

# Vercel deploy script — generated by ServerBuddy
echo "==> Logging in to Vercel"
vercel login

echo "==> Linking project (creates .vercel/project.json)"
vercel link

echo "==> Adding production environment variables (edit values!)"
vercel env add DATABASE_URL production
vercel env add AUTH_SECRET production

echo "==> Applying database migrations against the production DB"
npx prisma migrate deploy

echo "==> Deploying to production"
vercel --prod

echo "Done. 'vercel logs --prod' to stream runtime logs."
`;
}

/** Railway deploy script. */
export function generateRailwayScript(): string {
  return `#!/usr/bin/env bash
set -euo pipefail

# Railway deploy script — generated by ServerBuddy
echo "==> Install CLI once: npm i -g @railway/cli"
railway login

echo "==> Initialize + link project"
railway init

echo "==> Provision Postgres (creates DATABASE_URL automatically)"
railway add --database postgres

echo "==> Set app secrets"
railway variables --set "AUTH_SECRET=change-me"

echo "==> Deploy the current directory"
railway up

echo "Useful: railway logs, railway status, railway domain"
`;
}

