export const RUNBOOKS: Runbook[] = [VERCEL, RAILWAY, VPS_CADDY];

export function getRunbook(id: string): Runbook | undefined {
  return RUNBOOKS.find((r) => r.id === id);
}

/** Check quiz answers; returns the count correct + per-question verdicts. */
export function gradeQuiz(
  runbook: Runbook,
  answers: number[]
): { passed: boolean; correct: number; total: number; perQuestion: boolean[] } {
  const perQuestion = runbook.quiz.map((q, i) => answers[i] === q.correctIndex);
  const correct = perQuestion.filter(Boolean).length;
  return { passed: correct === runbook.quiz.length, correct, total: runbook.quiz.length, perQuestion };
}
