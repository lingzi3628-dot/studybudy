const dicts: Record<Lang, Dict> = { en, sw, fr, es, ar };

/**
 * Translate a key for the given language.
 * Supports {placeholder} interpolation, e.g. t("dash.reviewCards", "sw") returns "Pitia kadi {n}".
 * Pass a `params` object: t("dash.reviewCards", "sw", { n: 5 }) → "Pitia kadi 5".
 * Falls back to English if the key isn't found in the target language.
 */
export function t(key: string, lang: Lang = "en", params?: Record<string, string | number>): string {
  let str = dicts[lang]?.[key] ?? dicts.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

/**
 * Get the user's preferred UI language from localStorage or browser.
 */
export function getUILang(): Lang {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem("studybuddy_ui_lang");
  if (stored === "sw" || stored === "fr" || stored === "en" || stored === "es" || stored === "ar") return stored;
  // Auto-detect from browser
  const browser = navigator.language.toLowerCase();
  if (browser.startsWith("sw")) return "sw";
  if (browser.startsWith("fr")) return "fr";
  if (browser.startsWith("es")) return "es";
  if (browser.startsWith("ar")) return "ar";
  return "en";
}

/**
 * Set the user's preferred UI language.
 */
export function setUILang(lang: Lang): void {
  if (typeof window !== "undefined") {
    localStorage.setItem("studybuddy_ui_lang", lang);
    // Phase 45: set the document direction for RTL languages (Arabic)
    if (isRTL(lang)) {
      document.documentElement.setAttribute("dir", "rtl");
    } else {
      document.documentElement.setAttribute("dir", "ltr");
    }
  }
}
